#!/usr/bin/env python3
"""Generate the PLT -> import-name table from the shipped ELF.

The .plt is 3620 bytes: a 20-byte PLT0 followed by 300 entries of 12 bytes, matching the
300 R_ARM_JUMP_SLOT entries in .rel.plt. Entry n is at 0x297d4c + 12*n.

Usage:
    python3 recomp/gen_imports.py [--out runtime/imports_table.h]
"""
import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "recomp"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "runtime/imports_table.h"))
    args = ap.parse_args()

    import importlib.util
    spec = importlib.util.spec_from_file_location("elf_image", ROOT / "recomp/elf_image.py")
    elf_image = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(elf_image)

    img = elf_image.Image(ROOT / "analysis/apk/lib/armeabi-v7a/libFast5.so")
    jmprel = img.dyn[elf_image.DT_JMPREL]
    pltrelsz = img.dyn[elf_image.DT_PLTRELSZ]
    plt_base = 0x297D4C

    entries = []
    for i in range(pltrelsz // 8):
        off = jmprel + i * 8
        _r_offset, r_info = struct.unpack_from("<II", img.mem, off)
        sym = img.syms[r_info >> 8]
        entries.append((plt_base + i * 12, sym["name"]))

    lines = []
    lines.append("/* generated by recomp/gen_imports.py; do not edit */")
    lines.append("#ifndef FAST5_IMPORTS_TABLE_H")
    lines.append("#define FAST5_IMPORTS_TABLE_H")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct { uint32_t plt; const char *name; } ImportEntry;")
    lines.append("")
    lines.append("static const ImportEntry k_import_table[] = {")
    for plt, name in entries:
        lines.append(f'    {{ 0x{plt:06x}u, "{name}" }},')
    lines.append("};")
    lines.append("")
    lines.append(f"#define IMPORT_COUNT {len(entries)}u")
    lines.append("")
    lines.append("#endif")
    Path(args.out).write_text("\n".join(lines) + "\n")

    print(f"wrote {args.out} ({len(entries)} imports)")
    for plt, name in entries[:40]:
        print(f"  0x{plt:06x}  {name}")
    print("  ...")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
