#!/usr/bin/env python3
"""Emit, compile and link the entire translated library into one executable.

Two modes:
  * default: link the whole binary and execute one known function (the M2 link gate).
  * --boot:  link it, run the 433 .init_array constructors, then call appInit(800,480,0).

Both modes generate a global address -> function table that routes PLT addresses to the import
layer and Java-bridge addresses to runtime replacements.

Usage:
    python3 recomp/link_all.py analysis/reports/pcode_all.tsv [--test 0x29b014] [--jobs 8]
    python3 recomp/link_all.py analysis/reports/pcode_all.tsv --boot
"""
import argparse
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "recomp"))
from emit_c import Emitter, PRELUDE  # noqa: E402
from coverage import iter_funcs  # noqa: E402

IMAGE_END = 0x8B85BC
STACK_TOP = 0x8F0000

HEADER = """/* generated by recomp/link_all.py; do not edit */
#include "cpu.h"
#include "mem.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
"""


def write_if_changed(path: Path, text: str) -> bool:
    """Preserve mtimes of unchanged generated files so incremental builds can skip them."""
    if path.exists():
        try:
            if path.read_text() == text:
                return False
        except OSError:
            pass
    path.write_text(text)
    return True


def make_guest_image() -> None:
    import importlib.util
    import struct
    spec = importlib.util.spec_from_file_location("elf_image", ROOT / "recomp/elf_image.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    img = mod.Image(ROOT / "analysis/apk/lib/armeabi-v7a/libFast5.so")
    img.apply_relocations()
    patched = 0
    symbols = {"_ctype_": 0x9A1000, "_tolower_tab_": 0x9A1200, "_toupper_tab_": 0x9A1280}
    for off, name, _rtype in getattr(img, "undefined_relocs", []):
        if name in symbols:
            struct.pack_into("<I", img.mem, off, symbols[name])
            patched += 1
    print(f"guest data: patched {patched} libc slot(s)")
    (ROOT / "build/guest.bin").write_bytes(bytes(img.mem))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv")
    ap.add_argument("--test", default="0x29b014")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--chunk", type=int, default=200)
    ap.add_argument("--init", action="store_true", help="run .init_array constructors")
    ap.add_argument("--boot", action="store_true", help="run constructors then appInit")
    ap.add_argument("--emit-only", action="store_true", help="write chunks/table/main only")
    args = ap.parse_args()
    test_entry = int(args.test, 16)
    run_init = args.init or args.boot

    out = ROOT / "build/link"
    out.mkdir(parents=True, exist_ok=True)
    if not args.emit_only:
        for old in out.glob("*"):
            old.unlink()

    funcs = []
    bodies = []
    seen = set()
    tsv_paths = [Path(args.tsv)]
    extra_path = ROOT / "analysis/reports/pcode_extra.tsv"
    if extra_path.exists() and extra_path.resolve() != Path(args.tsv).resolve():
        tsv_paths.append(extra_path)
    for tsv_path in tsv_paths:
        for f in iter_funcs(tsv_path):
            if f.external or not f.insns or f.entry in seen:
                continue
            if 0x297D4C <= f.entry < 0x298B5C:      # PLT stubs are imports, not translated code
                continue
            seen.add(f.entry)
            funcs.append(f)
            bodies.append(Emitter(f).emit_body())

    chunks = []
    changed = 0
    for i in range(0, len(bodies), args.chunk):
        path = out / f"chunk_{i // args.chunk:03d}.c"
        text = (HEADER + PRELUDE + "\n"
                "void call_target(Cpu *c, uint8_t *mem, uint32_t target);\n"
                "void call_indirect(Cpu *c, uint8_t *mem, uint32_t target);\n"
                "void call_import(Cpu *c, uint8_t *mem, uint32_t plt);\n\n"
                + "\n".join(bodies[i:i + args.chunk]))
        if write_if_changed(path, text):
            changed += 1
        chunks.append(path)

    table = [HEADER]
    table.append("void call_target(Cpu *c, uint8_t *mem, uint32_t target);")
    table.append("void call_import(Cpu *c, uint8_t *mem, uint32_t plt);")
    table.append("int call_java(Cpu *c, uint8_t *mem, uint32_t target);")
    table.append("int call_override(Cpu *c, uint8_t *mem, uint32_t target);")
    table.append("Cpu *g_cpu;")
    for f in funcs:
        table.append(f"void fn_{f.entry:06x}(Cpu *c, uint8_t *mem);")
    table.append("")
    table.append("typedef struct {")
    table.append("    uint32_t addr;")
    table.append("    void (*fn)(Cpu *, uint8_t *);")
    table.append("} TargetEntry;")
    table.append("")
    table.append("static const TargetEntry target_table[] = {")
    for f in sorted(funcs, key=lambda x: x.entry):
        table.append(f"    {{0x{f.entry:06x}u, fn_{f.entry:06x}}},")
    table.append("};")
    table.append("")
    table.append("void call_target(Cpu *c, uint8_t *mem, uint32_t target) {")
    table.append("    g_cpu = c;")
    table.append("    if (call_java(c, mem, target)) { return; }")
    table.append("    if (target >= 0x297d4cu && target < 0x298b5cu) {")
    table.append("        call_import(c, mem, target);")
    table.append("        return;")
    table.append("    }")
    table.append("    if (call_override(c, mem, target)) { return; }")
    table.append("    size_t lo = 0, hi = sizeof(target_table) / sizeof(target_table[0]);")
    table.append("    while (lo < hi) {")
    table.append("        size_t mid = lo + (hi - lo) / 2;")
    table.append("        uint32_t addr = target_table[mid].addr;")
    table.append("        if (target == addr) { target_table[mid].fn(c, mem); return; }")
    table.append("        if (target < addr) hi = mid; else lo = mid + 1;")
    table.append("    }")
    table.append("    fprintf(stderr,")
    table.append('            "unmapped target 0x%08x r0=%08x r1=%08x r2=%08x r3=%08x "')
    table.append('            "r4=%08x r5=%08x r6=%08x r7=%08x r8=%08x r9=%08x r10=%08x "')
    table.append('            "r11=%08x r12=%08x sp=%08x lr=%08x\\n",')
    table.append("            target, c->r0, c->r1, c->r2, c->r3, c->r4, c->r5, c->r6,")
    table.append("            c->r7, c->r8, c->r9, c->r10, c->r11, c->r12, c->sp, c->lr);")
    table.append("    guest_fault(target, 1);")
    table.append("}")
    table.append("")
    table.append("void call_indirect(Cpu *c, uint8_t *mem, uint32_t target) {")
    table.append("    call_target(c, mem, target);")
    table.append("}")
    table_path = out / "table.c"
    if write_if_changed(table_path, "\n".join(table) + "\n"):
        changed += 1

    init_block = ""
    if run_init:
        init_block = f"""    uint32_t *init = (uint32_t *)(g_mem + 0x79f090u);
    for (unsigned i = 0; i < 433u; i++) {{
        Cpu ci;
        memset(&ci, 0, sizeof ci);
        ci.lr = 0xDEADBEE0u;
        ci.sp = {STACK_TOP:#x}u;
        call_target(&ci, g_mem, init[i]);
    }}
    fprintf(stderr, "constructors: 433 completed\\n");
"""

    common = f"""#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <execinfo.h>
#include <unistd.h>
#include "cpu.h"
#include "mem.h"

void call_target(Cpu *c, uint8_t *mem, uint32_t target);
void call_indirect(Cpu *c, uint8_t *mem, uint32_t target);
void fn_29c830(Cpu *c, uint8_t *mem);
void fn_29cb14(Cpu *c, uint8_t *mem);
void fn_29cac8(Cpu *c, uint8_t *mem);
void fn_29cf94(Cpu *c, uint8_t *mem);
void fn_29d1a0(Cpu *c, uint8_t *mem);
void init_guest_data(uint8_t *mem, uint32_t size);

uint32_t guest_mem_size;
static uint8_t *g_mem;

void guest_fault(uint32_t addr, int write) {{
    extern Cpu *g_cpu;
    fprintf(stderr, "guest fault at 0x%08x (%s)\\n", addr, write ? "write" : "read");
    if (g_cpu) {{
        fprintf(stderr, "guest regs r0=%08x r1=%08x r2=%08x r3=%08x r4=%08x r5=%08x "
                "r6=%08x r7=%08x r8=%08x r9=%08x r10=%08x r11=%08x r12=%08x "
                "sp=%08x lr=%08x pc=%08x\\n",
                g_cpu->r0, g_cpu->r1, g_cpu->r2, g_cpu->r3, g_cpu->r4, g_cpu->r5,
                g_cpu->r6, g_cpu->r7, g_cpu->r8, g_cpu->r9, g_cpu->r10, g_cpu->r11,
                g_cpu->r12, g_cpu->sp, g_cpu->lr, g_cpu->pc);
    }}
    void *bt[24];
    int n = backtrace(bt, 24);
    backtrace_symbols_fd(bt, n, 2);
    exit(3);
}}

int main(void) {{
    size_t size = 0x10000000;              /* 256 MiB guest address space */
    g_mem = calloc(1, size);
    if (!g_mem) return 2;
    FILE *f = fopen("build/guest.bin", "rb");
    if (!f) {{ perror("build/guest.bin"); return 2; }}
    if (fread(g_mem, 1, {IMAGE_END:#x}, f) != {IMAGE_END:#x}) {{ return 2; }}
    fclose(f);
    guest_mem_size = (uint32_t)size;
    init_guest_data(g_mem, guest_mem_size);
{init_block}"""

    if args.boot:
        main_c = common + f"""
    Cpu c;
    memset(&c, 0, sizeof c);
    c.r0 = 800u;
    c.r1 = 480u;
    c.r2 = 0u;
    c.lr = 0xDEADBEE0u;
    c.sp = {STACK_TOP:#x}u;
    fprintf(stderr, "calling appInit(800,480,0)\\n");
    fn_29c830(&c, g_mem);
    fprintf(stderr, "appInit returned r0=%u pc=0x%08x\\n", c.r0, c.pc);
    *(uint32_t *)(g_mem + 0x8B85A0) = c.r0;   /* the Java wrapper stores the Application* here */
    {{
        uint32_t gp = *(uint32_t *)(g_mem + 0x7F980C);
        uint32_t ap = *(uint32_t *)(g_mem + 0x7F8758);
        fprintf(stderr, "gates wait=%d game=%08x orient=%08x app=%08x scale=%f\\n",
                (int)*(uint32_t *)(g_mem + 0x8B859C), gp,
                gp ? *(uint32_t *)(g_mem + gp + 0x114) : 0, ap,
                ap ? *(float *)(g_mem + ap + 600) : 0.0f);
    }}

    Cpu s;
    memset(&s, 0, sizeof s);
    s.sp = {STACK_TOP:#x}u;
    s.lr = 0xDEADBEE0u;
    fprintf(stderr, "calling appResume()\\n");
    fn_29cac8(&s, g_mem);

    Cpu r;
    memset(&r, 0, sizeof r);
    r.sp = {STACK_TOP:#x}u;
    r.lr = 0xDEADBEE0u;
    fprintf(stderr, "calling appRender()\\n");
    fn_29cb14(&r, g_mem);
    fprintf(stderr, "appRender returned r0=%u pc=0x%08x\\n", r.r0, r.pc);

    for (int i = 0; i < 200; i++) {{
        Cpu f;
        memset(&f, 0, sizeof f);
        f.sp = {STACK_TOP:#x}u;
        f.lr = 0xDEADBEE0u;
        fn_29cb14(&f, g_mem);
        if (i == 60) {{
            Cpu t;
            memset(&t, 0, sizeof t);
            t.r0 = 400u;
            t.r1 = 240u;
            t.r2 = 0u;
            t.sp = {STACK_TOP:#x}u;
            t.lr = 0xDEADBEE0u;
            fprintf(stderr, "touch press\\n");
            fn_29cf94(&t, g_mem);
        }}
        if (i == 70) {{
            Cpu t;
            memset(&t, 0, sizeof t);
            t.r0 = 400u;
            t.r1 = 240u;
            t.r2 = 0u;
            t.sp = {STACK_TOP:#x}u;
            t.lr = 0xDEADBEE0u;
            fprintf(stderr, "touch release\\n");
            fn_29d1a0(&t, g_mem);
        }}
        if (i % 30 == 0) fprintf(stderr, "frame %d pc=0x%08x\\n", i, f.pc);
        usleep(20000);
    }}
    return 0;
}}
"""
        main_path = out / "main_boot.c"
        exe = ROOT / "build/fast5_boot_test"
    else:
        main_c = common + f"""
    Cpu c;
    memset(&c, 0, sizeof c);
    c.lr = 0xDEADBEE0u;
    c.sp = {STACK_TOP:#x}u;
    fn_{test_entry:06x}(&c, g_mem);
    printf("fn_{test_entry:06x}: r0=%u pc=0x%08x\\n", c.r0, c.pc);
    return 0;
}}
"""
        main_path = out / "main_test.c"
        exe = ROOT / "build/fast5_recomp_test"

    if write_if_changed(main_path, main_c):
        changed += 1
    if args.emit_only:
        generated = set(chunks + [table_path, main_path])
        for old in out.glob("chunk_*.c"):
            if old not in generated:
                old.unlink()
                changed += 1
        for name in ("main_boot.c", "main_test.c"):
            old = out / name
            if old.exists() and old not in generated:
                old.unlink()
                changed += 1
        make_guest_image()
        print(f"emitted {len(chunks)} chunks and {len(funcs)} functions "
              f"({changed} file(s) changed, no compile)")
        return 0

    def compile_one(path: Path):
        obj = path.with_suffix(".o")
        opt = "-O0" if path.name == "table.c" else "-O1"
        proc = subprocess.run(
            ["gcc", "-std=c11", opt, "-Wall", "-Wextra",
             "-I", str(ROOT / "runtime"), "-c", str(path), "-o", str(obj)],
            capture_output=True, text=True)
        return path, proc.returncode, proc.stderr

    sources = chunks + [out / "table.c", main_path]
    results = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for res in pool.map(compile_one, sources):
            results.append(res)

    runtime_objs = []
    for name in ("imports.c", "java_bridge.c", "guest_data.c", "vfs.c", "overrides.c"):
        src = ROOT / "runtime" / name
        obj = out / (Path(name).stem + ".o")
        proc = subprocess.run(
            ["gcc", "-std=c11", "-O1", "-Wall", "-Wextra",
             "-I", str(ROOT / "runtime"), "-c", str(src), "-o", str(obj)],
            capture_output=True, text=True)
        if proc.returncode != 0:
            print(f"RUNTIME COMPILE FAILED: {name}")
            print(proc.stderr[:4000])
            return 1
        runtime_objs.append(str(obj))

    failures = [(p.name, rc, err) for p, rc, err in results if rc != 0]
    if failures:
        for name, rc, err in failures[:5]:
            print(f"COMPILE FAIL {name} ({rc})\n{err[:2000]}")
        return 1
    print(f"compiled {len(sources)} translation units ({len(funcs)} functions)")

    make_guest_image()
    objs = [str(p.with_suffix(".o")) for p in sources] + runtime_objs
    link = subprocess.run(["gcc", *objs, "-o", str(exe), "-lm", "-rdynamic"],
                          capture_output=True, text=True)
    if link.returncode != 0:
        print("LINK FAILED")
        print(link.stderr[:4000])
        return 1
    print(f"linked {exe}")

    run = subprocess.run([str(exe)], cwd=ROOT, capture_output=True, text=True)
    print(run.stdout.strip())
    if run.returncode != 0:
        print(run.stderr.strip())
    return run.returncode


if __name__ == "__main__":
    raise SystemExit(main())
