#!/usr/bin/env python3
"""Emit every function to C and compile the generated code.

This is the whole-binary syntax/semantics gate: it does not link or run, it proves the
emitter produces valid C for every function in the library.

Output:
    build/all/chunk_XXX.c / .o
    analysis/reports/emit-all.md

Usage:
    python3 recomp/emit_all.py analysis/reports/pcode.tsv [--chunk 200] [--jobs 8]
"""
import argparse
import subprocess
import sys
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "recomp"))
from pcode import Func  # noqa: E402
from emit_c import Emitter, PRELUDE  # noqa: E402
from coverage import iter_funcs  # noqa: E402

HEADER = """/* generated by recomp/emit_all.py; do not edit */
#include "cpu.h"
#include "mem.h"
#include <math.h>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv")
    ap.add_argument("--chunk", type=int, default=200)
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--keep", action="store_true", help="keep generated .c files")
    args = ap.parse_args()

    out_dir = ROOT / "build/all"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("chunk_*.c"):
        old.unlink()
    for old in out_dir.glob("chunk_*.o"):
        old.unlink()

    emit_fail = []
    chunks = []
    buf = []

    for f in iter_funcs(Path(args.tsv)):
        if f.external or not f.insns:
            continue
        try:
            buf.append(Emitter(f).emit_body())
        except Exception as ex:  # noqa: BLE001
            emit_fail.append((f.entry, f.name, str(ex)))
            continue
        if len(buf) >= args.chunk:
            chunks.append(buf)
            buf = []
    if buf:
        chunks.append(buf)

    c_files = []
    for ci, bodies in enumerate(chunks):
        path = out_dir / f"chunk_{ci:03d}.c"
        text = (HEADER + PRELUDE + "\n"
                "void call_target(Cpu *c, uint8_t *mem, uint32_t target);\n"
                "void call_indirect(Cpu *c, uint8_t *mem, uint32_t target);\n\n"
                + "\n".join(bodies))
        path.write_text(text)
        c_files.append(path)

    def compile_one(path: Path):
        obj = path.with_suffix(".o")
        proc = subprocess.run(
            ["gcc", "-std=c11", "-O1", "-Wall", "-Wextra",
             "-I", str(ROOT / "runtime"), "-c", str(path), "-o", str(obj)],
            capture_output=True, text=True)
        return path, proc.returncode, proc.stderr

    results = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for res in pool.map(compile_one, c_files):
            results.append(res)

    errors = Counter()
    warnings = Counter()
    failed_files = []
    for path, rc, stderr in results:
        for line in stderr.splitlines():
            if "error:" in line:
                msg = line.split("error:", 1)[1].strip()
                errors[msg] += 1
            elif "warning:" in line:
                msg = line.split("warning:", 1)[1].strip()
                warnings[msg] += 1
        if rc != 0:
            failed_files.append(path.name)

    total_funcs = sum(len(b) for b in chunks)
    lines = []
    lines.append("# Whole-binary emit + compile\n")
    lines.append(f"- Functions emitted: **{total_funcs:,}** in {len(c_files)} chunks")
    lines.append(f"- Emitter failures: {len(emit_fail)}")
    lines.append(f"- Chunks compiled cleanly: **{len(c_files) - len(failed_files)}/{len(c_files)}**")
    lines.append(f"- Distinct errors: {len(errors)}, distinct warnings: {len(warnings)}\n")
    if emit_fail:
        lines.append("## Emitter failures\n")
        for entry, name, err in emit_fail[:20]:
            lines.append(f"- `0x{entry:06x}` {name}: {err}")
        lines.append("")
    if errors:
        lines.append("## Compiler errors\n")
        lines.append("| Error | Count |")
        lines.append("|---|---|")
        for msg, count in errors.most_common(30):
            lines.append(f"| `{msg}` | {count} |")
        lines.append("")
    if warnings:
        lines.append("## Compiler warnings\n")
        lines.append("| Warning | Count |")
        lines.append("|---|---|")
        for msg, count in warnings.most_common(30):
            lines.append(f"| `{msg}` | {count} |")
        lines.append("")

    report = "\n".join(lines) + "\n"
    (ROOT / "analysis/reports/emit-all.md").write_text(report)
    print(report)
    if not args.keep:
        for path in c_files:
            path.unlink()
    return 0 if not errors and not emit_fail else 1


if __name__ == "__main__":
    raise SystemExit(main())
